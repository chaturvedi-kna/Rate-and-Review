def get_random_review() -> str:
    """Returns a single random authentic review from the dataset."""
    return random.choice(GENERIC_REVIEWS)


def get_review_batch(count: int) -> List[str]:
    """Returns a list of `count` unique or shuffled reviews from the dataset."""
    if count <= len(GENERIC_REVIEWS):
        return random.sample(GENERIC_REVIEWS, count)
    # If more than dataset length, sample with replacement
    shuffled = random.sample(GENERIC_REVIEWS, len(GENERIC_REVIEWS))
    needed = count - len(GENERIC_REVIEWS)
    return shuffled + [random.choice(GENERIC_REVIEWS) for _ in range(needed)]


def resolve_rating_and_comment(
    rating_mode: str = "5",
    review_mode: str = "auto",
    custom_comment: str = "",
) -> Tuple[int, str]:
    """
    Resolves rating stars and review comments based on chosen mode:
    - rating_mode:
        '5' or '5_only' -> 5 Stars
        '4' or '4_only' -> 4 Stars
        'combo_4_5' -> Natural mix (~75% 5 Stars, ~25% 4 Stars)
    - review_mode:
        'auto' -> Random curated authentic review from the pool
        'custom' -> Use user provided custom_comment (fallback to auto if empty)
    """
    # 1. Resolve Rating
    mode_str = str(rating_mode).lower().strip()
    if mode_str in ("4", "4_only"):
        stars = 4
    elif mode_str in ("combo_4_5", "combo", "4_5_combo", "mixed"):
        # 75% 5-star, 25% 4-star natural ratio
        stars = random.choices([5, 4], weights=[75, 25], k=1)[0]
    else:
        stars = 5

    # 2. Resolve Review Comment
    c_text = (custom_comment or "").strip()
    if review_mode == "custom" and c_text:
        comment = c_text
    else:
        comment = get_random_review()

    return stars, comment

